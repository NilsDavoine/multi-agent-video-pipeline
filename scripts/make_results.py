"""Generate results.md from real measurements. Nothing in results.md is typed by hand.

Inputs: examples/<slug>/qc.json and run.json (written by the pipeline), the video
file itself (ffprobe), a fresh pytest run (unit + example), results/mutation.json.
"""
from __future__ import annotations

import json
import platform
import subprocess
import sys
from datetime import datetime, timezone
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EX = ROOT / "examples" / "how-to-read-an-invoice"


def pytest(*args: str) -> str:
    out = subprocess.run([sys.executable, "-m", "pytest", "-q", *args], cwd=ROOT,
                         capture_output=True, text=True).stdout.strip().splitlines()
    return out[-1] if out else "no output"


def probe(video: Path) -> dict:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                          "stream=codec_type,width,height,r_frame_rate,duration", "-of", "json", str(video)],
                         capture_output=True, text=True, check=True).stdout
    return {s["codec_type"]: s for s in json.loads(out)["streams"]}


def main() -> None:
    qc = json.loads((EX / "qc.json").read_text())
    run = json.loads((EX / "run.json").read_text())
    mut = json.loads((ROOT / "results" / "mutation.json").read_text())
    timeline = json.loads((EX / "timeline.json").read_text())
    video = EX / "final.mp4"
    st = probe(video)
    unit = pytest()
    example = pytest("-m", "example")

    L = ["# Results", "",
         f"_Generated by `scripts/make_results.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC "
         f"({platform.system()}, Python {platform.python_version()}). Do not edit by hand._", "",
         "## Example video", "",
         f"- File: `examples/how-to-read-an-invoice/final.mp4`, {video.stat().st_size / 1e6:.2f} MB, "
         f"{st['video']['width']}x{st['video']['height']}, {float(Fraction(st['video']['r_frame_rate'])):.0f} fps, "
         f"{float(st['video']['duration']):.2f} s, {len(timeline['scenes'])} scenes",
         f"- Agents provider for this run: `{run['provider']}`"
         + (" (recorded answers, no API call)" if run["provider"] == "replay" else ""),
         f"- Recordings out of date with the prompts: {len(run['stale_recordings'])}",
         f"- QC status: **{qc['status'].upper()}**", "",
         "## Quality gates (measured on the final file)", "",
         "| Gate | Value | Threshold | Result | Detail |", "|---|---|---|---|---|"]
    for c in qc["checks"]:
        detail = c["detail"].replace("|", "/")
        L.append(f"| `{c['name']}` | {c['value']} | {c['threshold']} | {'pass' if c['passed'] else 'FAIL'} "
                 f"| {detail} |")
    first = ROOT / "results" / "first_render_qc.json"
    if first.exists():
        fr = json.loads(first.read_text())
        L += ["", "## First render of the example (before the layout fix)", "",
              f"Status: **{fr['status']}**. Failing gates:", ""]
        L += [f"- `{c['name']}` = {c['value']} (threshold {c['threshold']}): {c['detail']}"
              for c in fr["checks"] if not c["passed"]] or ["- none"]
    L += ["", "## Guard tested by mutation", "",
          f"- Mutation: {mut['mutation']}",
          f"- Status of the mutated video: **{mut['status_on_mutated_video']}**"]
    for name, c in mut["gate_on_mutated_video"].items():
        L.append(f"- `{name}` on the mutated video: {c['value']} (threshold {c['threshold']}, "
                 f"{'pass' if c['passed'] else 'FAIL'}); {c['detail']}")
    L += [f"- Guard test exit code: mutated = {mut['guard_test_exit_code']['mutated']} (red), "
          f"restored = {mut['guard_test_exit_code']['restored']} (green)",
          f"- Restored from a backup copy (not git); identical hash: {mut['restored_identical']}",
          f"- Guard works: **{mut['guard_works']}** (run {mut['when']})", "",
          "## Tests", "",
          f"- Unit tests (`pytest`): {unit}",
          f"- Example tests with local models (`pytest -m example`): {example}", "",
          "## Stage timings of the example run", "",
          "| Step | Status | Seconds |", "|---|---|---|"]
    for e in run["events"]:
        L.append(f"| {e['step']} | {e['status']} | {e['seconds']} |")
    total = sum(e["seconds"] for e in run["events"])
    L += [f"| **total (excluding QC)** | | {total:.1f} |", ""]
    (ROOT / "results.md").write_text("\n".join(L))
    print("\n".join(L))

    # Same numbers, compact, between markers in the README.
    short = [f"Example video: {float(st['video']['duration']):.1f} s, {len(timeline['scenes'])} scenes, "
             f"status **{qc['status']}**. Mutated video (off-script voice in one scene): "
             f"**{mut['status_on_mutated_video']}**.", "",
             "| Gate | Measured | Threshold |", "|---|---|---|"]
    short += [f"| `{c['name']}` | {c['value']} | {c['threshold']} |" for c in qc["checks"]]
    w = mut["gate_on_mutated_video"]["transcript_wer_worst_scene"]
    short += [f"| `transcript_wer_worst_scene`, mutated video | {w['value']} | {w['threshold']} |", "",
              f"Tests: unit {unit}; example {example}."]
    readme = (ROOT / "README.md").read_text()
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    head, rest = readme.split(start)
    _, tail = rest.split(end)
    (ROOT / "README.md").write_text(head + start + "\n" + "\n".join(short) + "\n" + end + tail)


if __name__ == "__main__":
    main()
